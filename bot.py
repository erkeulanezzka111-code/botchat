# Мақал батырмалары (Өзгертілмеді)
def get_proverb_keyboard(category_key: str, index: int) -> InlineKeyboardMarkup:
    total = len(PROVERBS[category_key]["items"])
    prev_idx = total - 1 if index == 0 else index - 1
    next_idx = 0 if index == total - 1 else index + 1

    buttons = [
        [
            InlineKeyboardButton(text="⬅️ Артқа", callback_data=f"nav:{category_key}:{prev_idx}"),
            InlineKeyboardButton(text=f"{index + 1}/{total}", callback_data="ignore"),
            InlineKeyboardButton(text="Келесі ➡️", callback_data=f"nav:{category_key}:{next_idx}")
        ],
        [InlineKeyboardButton(text="🔍 Кешенді лингвистикалық талдау", callback_data=f"analiz:{category_key}:{index}")],
        [InlineKeyboardButton(text="📜 Басты менюге оралу", callback_data="go_to_menu")]
    ]
    return InlineKeyboardMarkup(inline_keyboard=buttons)

