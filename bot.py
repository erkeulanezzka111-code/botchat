@dp.callback_query(F.data.startswith("play_game:"))
async def open_game_link(callback: types.CallbackQuery):
    game_key = callback.data.split(":")[1]
    game_info = GAMES_DATA.get(game_key)
    
    if not game_info:
        await callback.answer("Жаттығу табылмады!", show_alert=True)
        return

    text = f"🎯 **{game_info['title']}**\n\nТапсырманы орындау үшін төмендегі батырманы басыңыз:"
    markup = get_single_game_keyboard(game_key)
    
    try:
        await callback.message.edit_text(text=text, parse_mode="Markdown", reply_markup=markup)
    except Exception:
        await callback.message.delete()
        await callback.message.answer(text=text, parse_mode="Markdown", reply_markup=markup)
    await callback.answer()

@dp.callback_query(F.data.startswith(("show:", "nav:")))
async def handle_pagination(callback: types.CallbackQuery):
    _, category_key, index_str = callback.data.split(":")
    index = int(index_str)
    
    cat_info = PROVERBS[category_key]
    item_data = cat_info["items"][index]
    
    text = f"📌 **{cat_info['title']}**\n\n{item_data['text']}"
    image_source = item_data['image']
    markup = get_proverb_keyboard(category_key, index)

    if callback.data.startswith("show:"):
        try:
            await callback.message.answer_photo(
                photo=image_source,
                caption=text,
                parse_mode="Markdown",
                reply_markup=markup
            )
            await callback.message.delete()
        except Exception:
            await callback.message.answer(
                text=text + "\n\n*(Картинка недоступна)*",
                parse_mode="Markdown",
                reply_markup=markup
            )
            try:
                await callback.message.delete()
            except:
                pass
    else:
        try:
            await callback.message.edit_media(
                media=InputMediaPhoto(media=image_source, caption=text, parse_mode="Markdown"),
                reply_markup=markup
            )
        except Exception:
            await callback.message.edit_text(
                text=text + "\n\n*(Картинка недоступна)*",
                parse_mode="Markdown",
                reply_markup=markup
            )
            
    await callback.answer()

